#!/usr/bin/env python3
"""Generate imports_gen.cpp: one C++ function per system import of a PS3 EBOOT.

The EBOOT calls the PS3 system libraries through 32-byte stubs. XenonRecomp translates
them as weak functions; this script emits strong versions with the same names
(sub_XXXXXXXX) that call ps3_import(ctx, base, index). The runtime decides what each
import does, using the g_imports table (stub address, module, NID, name).

Usage: python tools/ps3/gen_imports.py EBOOT.elf tools/ps3/nids.csv > imports_gen.cpp
Standard library only.
"""
import csv
import struct
import sys


def main():
    elf, nidcsv = sys.argv[1], sys.argv[2]
    d = open(elf, 'rb').read()
    phoff = struct.unpack_from('>Q', d, 0x20)[0]
    phentsize, phnum = struct.unpack_from('>HH', d, 0x36)
    segs, prx = [], None
    for i in range(phnum):
        o = phoff + i * phentsize
        typ = struct.unpack_from('>I', d, o)[0]
        off, va, _pa, fsz = struct.unpack_from('>QQQQ', d, o + 8)
        if typ == 1 and fsz:
            segs.append((va, off, fsz))
        if typ == 0x60000002:
            prx = va

    def rd(a, n):
        for va, off, sz in segs:
            if va <= a < va + sz:
                return d[off + a - va: off + a - va + n]
        raise ValueError(hex(a))

    def u32(a):
        return struct.unpack('>I', rd(a, 4))[0]

    def cstr(a):
        return rd(a, 64).split(b'\0')[0].decode()

    names = {}
    for r in csv.DictReader(open(nidcsv, encoding='utf-8')):
        names[int(r['nid'], 16)] = r['name']

    # sys_process_prx_info: +0x18 start of the library stub table, +0x1C end
    a, fin = u32(prx + 0x18), u32(prx + 0x1C)
    slots = {}
    while a < fin:
        size = rd(a, 1)[0]
        nf = struct.unpack('>H', rd(a + 6, 2))[0]
        mod, nids, addrs = cstr(u32(a + 0x10)), u32(a + 0x14), u32(a + 0x18)
        for i in range(nf):
            nid = u32(nids + 4 * i)
            slots[addrs + 4 * i] = (mod, nid, names.get(nid, 'nid_%08x' % nid))
        a += size

    # Stubs: li r12,0 / oris r12,r12,HI / lwz r12,LO(r12) / ... / bctr  (32 bytes)
    code = [s for s in segs if s[0] == 0x10000][0]
    stubs = []
    pos = code[0]
    end = code[0] + code[2] - 32
    while pos < end:
        w0, w1, w2 = u32(pos), u32(pos + 4), u32(pos + 8)
        if w0 == 0x39800000 and (w1 >> 16) == 0x658C and (w2 >> 16) == 0x818C:
            lo = struct.unpack('>h', struct.pack('>H', w2 & 0xFFFF))[0]
            slot = ((w1 & 0xFFFF) << 16) + lo
            if slot in slots:
                stubs.append((pos, slots[slot]))
            pos += 32
        else:
            pos += 4

    print('// GENERATED by tools/ps3/gen_imports.py. Do not edit by hand.')
    print('#include "ppc_recomp_shared.h"')
    print('')
    print('void ps3_import(PPCContext& ctx, uint8_t* base, int idx);')
    print('')
    print('struct Ps3Import { uint32_t stub; const char* module; uint32_t nid; const char* name; };')
    print('extern const Ps3Import g_imports[] = {')
    for pos, (mod, nid, nom) in stubs:
        print('    { 0x%X, "%s", 0x%08X, "%s" },' % (pos, mod, nid, nom))
    print('};')
    print('extern const int g_num_imports = %d;' % len(stubs))
    print('')
    for i, (pos, (mod, nid, nom)) in enumerate(stubs):
        print('PPC_FUNC(sub_%X) { ps3_import(ctx, base, %d); } // %s::%s' % (pos, i, mod, nom))
    print('// %d imports' % len(stubs), file=sys.stderr)


if __name__ == '__main__':
    main()
